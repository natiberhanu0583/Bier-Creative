• **"ዘመዴ/ጓደኛዬ በነጻ ይሰራልኛል":** አክብር፤ ሙያዊ ስራ፣ ወጥነት፣ ድጋፍ እና ጊዜ ገደብ ዋጋ ይሰጣል፤ ለወደፊት ሲፈልጉ እዚህ እንደሆንን ንገር።
• **"አላምናችሁም":** ፖርትፎሊዮ፣ እውነተኛ ቢሮ (ደብረ ብርሃን)፣ ውል፣ ከመለጠፉ በፊት ማጽደቅ፣ ቢሮ ጎብኝተው ማነጋገር።
• **"ዌብሳይት አያስፈልገኝም፣ Facebook አለኝ":** ሁለቱ ለየብቻ ሚና እንዳላቸው አስረዳ (website_vs_social)፤ ሲዘጋጁ እንደሚጨመር ንገር።

